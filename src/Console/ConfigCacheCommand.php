<?php

declare(strict_types=1);

namespace Tavaan\Engine\Config\Console;

use Tavaan\Engine\Config\Contracts\RepositoryInterface;

/**
 * Command `config:cache` — کش همهٔ پیکربندی‌ها در یک فایل.
 */
final class ConfigCacheCommand
{
    public function __construct(
        private readonly RepositoryInterface $config,
    ) {
    }

    public function name(): string
    {
        return 'config:cache';
    }

    public function description(): string
    {
        return 'کش پیکربندی برای production.';
    }

    public function handle(array $args = []): int
    {
        $target = $args[0] ?? 'storage/config.php';
        $items = $this->config->all();
        $content = "<?php

declare(strict_types=1);

// Cached config generated by tvn config:cache.
return " . \var_export($items, true) . ";
";
        if (\file_put_contents($target, $content) === false) {
            echo "Failed to write cache file: {$target}
";
            return 1;
        }
        echo "Config cached to: {$target}
";
        return 0;
    }
}
